# Personal Life OS Android App

This repository has been converted from a static GitHub Pages landing page into an Android app concept for a personal life dashboard.

## What this app includes
- Dark, modern productivity dashboard UI
- Focus on goals, routines, habits, and daily planning
- Material 3 + Jetpack Compose layout
- Mobile-friendly sections inspired by the original design

## Getting started
1. Open the project in Android Studio.
2. Let Gradle sync.
3. Run the `app` configuration on an Android emulator or connected device.

## App structure
- `app/src/main/java/com/personal/os/MainActivity.kt` — app entry point
- `app/src/main/java/com/personal/os/PersonalLifeOSApp.kt` — dashboard UI
- `app/src/main/res/values/` — styles and app metadata

## Design inspiration
The app keeps the original "Personal Life OS" aesthetic: a dark theme, blue accent colors, rounded cards, and clarity-first productivity UI.

## Notes
This is a strong mobile-first conversion of the repository concept and can be extended with actual task tracking, goals persistence, or habit reminders next.
